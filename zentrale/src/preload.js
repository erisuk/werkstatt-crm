// Schmale, sichere Brücke zwischen Oberfläche und Hauptprozess.
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('zentrale', {
  platform: process.platform,
  getState: () => ipcRenderer.invoke('get-state'),
  openSession: (args) => ipcRenderer.invoke('open-session', args),
  newSession: (args) => ipcRenderer.invoke('new-session', args),
  send: (text) => ipcRenderer.invoke('send-message', text),
  stopChat: () => ipcRenderer.invoke('stop-chat'),
  respondApproval: (id, decision) => ipcRenderer.invoke('approval-respond', { id, decision }),
  pickFolder: () => ipcRenderer.invoke('pick-folder'),
  saveTask: (task) => ipcRenderer.invoke('tasks-save', task),
  toggleTask: (id) => ipcRenderer.invoke('tasks-toggle', id),
  removeTask: (id) => ipcRenderer.invoke('tasks-remove', id),
  runTask: (id) => ipcRenderer.invoke('tasks-run', id),
  updateSettings: (patch) => ipcRenderer.invoke('settings-update', patch),
  listConnections: () => ipcRenderer.invoke('connections-list'),
  macToday: (launch) => ipcRenderer.invoke('mac-today', { launch: launch === true }),
  macTest: () => ipcRenderer.invoke('mac-test'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  setTopic: (ids, topic) => ipcRenderer.invoke('session-topic', { ids, topic }),
  trashSessions: (ids) => ipcRenderer.invoke('sessions-trash', { ids }),
  trashProjectFolder: (dir) => ipcRenderer.invoke('project-folder-trash', dir),
  library: () => ipcRenderer.invoke('library'),
  toggleAgent: (id, active) => ipcRenderer.invoke('agent-toggle', { id, active }),
  runningWork: () => ipcRenderer.invoke('running-work'),
  macApps: () => ipcRenderer.invoke('mac-apps'),
  fsFavorites: () => ipcRenderer.invoke('fs-favorites'),
  fsList: (dir, hidden) => ipcRenderer.invoke('fs-list', { path: dir, hidden: hidden === true }),
  fsIcon: (p) => ipcRenderer.invoke('fs-icon', p),
  fsOpen: (p) => ipcRenderer.invoke('fs-open', p),
  fsReveal: (p) => ipcRenderer.invoke('fs-reveal', p),
  fsTrash: (p) => ipcRenderer.invoke('fs-trash', p),
  fsSearch: (q) => ipcRenderer.invoke('fs-search', q),
  onState: (fn) => ipcRenderer.on('state', (_e, s) => fn(s)),
  onChatEvent: (fn) => ipcRenderer.on('chat-event', (_e, ev) => fn(ev)),
});
