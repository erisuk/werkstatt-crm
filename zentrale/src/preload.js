  toggleTask: (id) => ipcRenderer.invoke('tasks-toggle', id),
  removeTask: (id) => ipcRenderer.invoke('tasks-remove', id),
  runTask: (id) => ipcRenderer.invoke('tasks-run', id),
  updateSettings: (patch) => ipcRenderer.invoke('settings-update', patch),
  listConnections: () => ipcRenderer.invoke('connections-list'),
  macToday: (launch, part) => ipcRenderer.invoke('mac-today', { launch: launch === true, part }),
  macTest: () => ipcRenderer.invoke('mac-test'),
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  setTopic: (ids, topic) => ipcRenderer.invoke('session-topic', { ids, topic }),
  trashSessions: (ids) => ipcRenderer.invoke('sessions-trash', { ids }),
  trashProjectFolder: (dir) => ipcRenderer.invoke('project-folder-trash', dir),
  library: () => ipcRenderer.invoke('library'),
  toggleAgent: (id, active) => ipcRenderer.invoke('agent-toggle', { id, active }),
  readAgent: (id) => ipcRenderer.invoke('agent-read', id),
