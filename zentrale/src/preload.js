  runningWork: () => ipcRenderer.invoke('running-work'),
  macApps: () => ipcRenderer.invoke('mac-apps'),
  fsFavorites: () => ipcRenderer.invoke('fs-favorites'),
  fsList: (dir, hidden) => ipcRenderer.invoke('fs-list', { path: dir, hidden: hidden === true }),
  fsIcon: (p) => ipcRenderer.invoke('fs-icon', p),
  fsOpen: (p) => ipcRenderer.invoke('fs-open', p),
  fsReveal: (p) => ipcRenderer.invoke('fs-reveal', p),
